#ifndef TYPES_H
#define TYPES_H

// Do not change the declared function signatures.

/**
 * Read and print a string.
 */
void read_print_string(void);

/**
 * Read a string and print its length.
 */
void read_print_string_length(void);

/**
 * Read a string and print its letter and numeral counts.
 */
void read_print_string_alphnum(void);

/**
 * Read a string and print it with all letters in lowercase.
 */
void read_print_string_lower(void);

/**
 * Read a character and a string, and print the string with occurrences of the
 * character replaced.
 */
void read_print_string_replace(void);

/**
 * Read two strings and determine whether they are equal.
 */
void read_print_string_compare(void);

#endif
